"""Export the card data to sim/cards.js for the combat sim (SPEC section 2).

Usage: .venv/bin/python tools/export_sim.py
Never hand-edit sim/cards.js: change cards/base_set.py or cards/foes.py and run this (build_cards.py does too).
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "cards"))
import base_set as bs  # noqa: E402
import foes  # noqa: E402
from build_cards import foe_lines  # noqa: E402

OUT = ROOT / "sim" / "cards.js"
KEY_ORDER = ["id", "name", "rank", "kind", "type", "kw", "text", "strip", "group", "size", "req", "noisy", "uses", "atk",
             "fx", "deck"]


def num(v):
    return int(str(v).replace("−", "-"))


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def powers(plist, prefix, default_name):
    out = []
    for i, p in enumerate(plist):
        out.append({"id": f"{prefix}#{i}", **{"name": default_name, **p}})
    return out


def export_card(c):
    kw = c["kw"].split(" · ")
    req = re.search(r"Req (STR|DEX|INT|WIL) \+(\d+)", c["kw"])
    noisy = re.search(r"Noisy (\d+)", c["kw"])
    out = {"id": c["id"], "name": c["name"], "rank": c["rank"], "kind": c["kind"], "type": kw[0], "kw": kw,
           "text": c["text"], "strip": {k: num(v) for k, v in c["strip"].items()}, "group": c["group"]}
    if kw[0] == "Core":
        out["size"] = kw[1]
    if req:
        out["req"] = {req[1]: int(req[2])}
    if noisy:
        out["noisy"] = int(noisy[1])
    if "uses" in c:
        out["uses"] = c["uses"]
    if "atk" in c:
        out["atk"] = c["atk"]
    out["fx"] = powers(c.get("fx", []), c["id"], c["name"])
    deck = next((d for d in bs.DECKS if d["cover"] is c), None)
    if deck:
        out["deck"] = c["id"]
    return {k: out[k] for k in KEY_ORDER if k in out}


def export_deck(d):
    cover = d["cover"]
    ps = []
    for s in d["cards"]:
        p = {"id": f'{cover["id"]}#{slug(s["name"])}', **s["fx"]}
        if "form" in p:
            p["form"] = dict(p["form"])
        ps.append(p)
    return {"cover": cover["id"], **d["stats"], "powers": ps}


def export_foe(f):
    values, *_ = foe_lines(f)
    core = bs.BY_NAME[f["core"]]["id"] if f["core"] else None
    body = None
    if f["body"]:
        s, d, i, w, hp, spd, size = f["body"]
        body = {"STR": s, "DEX": d, "INT": i, "WIL": w, "HP": hp, "SPD": spd, "size": size}
    senses = {}
    m = re.fullmatch(r"Darkvision (\d+)", f["senses"])
    if m:
        senses["darkvision"] = int(m[1])
    elif f["senses"]:
        raise ValueError(f"unknown sense: {f['senses']}")
    extra = f["extra_dice"]
    if isinstance(extra, dict):  # per weapon: {card id: n}
        extra = {bs.BY_NAME[n]["id"]: k for n, k in extra.items()}
    recharge = {}  # {power id: n}: the card's limited-use powers become Recharge n–6
    for name, n in f["recharge"].items():
        c = bs.BY_NAME[name]
        ids = [p["id"] for p in powers(c.get("fx", []), c["id"], c["name"]) if "uses" in p]
        if not ids:
            raise ValueError(f"{f['name']}: {name} has no limited-use power to recharge")
        recharge.update({i: n for i in ids})
    return {"name": f["name"], "core": core, "body": body, "carries": [bs.BY_NAME[n]["id"] for n in f["carries"]],
            "bonus": f["bonus"], "extraDice": extra, "recharge": recharge, "powers": f["powers"], "senses": senses,
            "alert": f["alert"], "boss": f["boss"], "own": f["own"],
            "ownFx": powers(f["own_fx"], f"foe-{slug(f['name'])}", f["name"]),
            "totals": {k: num(v) for k, v in values.items()}}


def build():
    base = {"armor": 1, "hand": 2, "jewelry": 1, "item": 2, "aspect": 3}  # starting Slots per player (P 3.2)
    frames = [{"key": key, "name": name, "perPlayer": base[key]} for key, name, *_ in bs.FRAMES
              if key in base and name.lower() == key]
    return {
        "version": 1,
        "cards": {c["id"]: export_card(c) for c in sorted(bs.CARDS, key=lambda c: c["id"])},
        "decks": {d["cover"]["id"]: export_deck(d) for d in bs.DECKS},
        "foes": [export_foe(f) for f in foes.FOES],
        "frames": frames,
        "starter": {k: [bs.BY_NAME[n]["id"] for n in v] for k, v in bs.STARTER_LIST.items()},
    }


def main():
    body = json.dumps(build(), indent=1, ensure_ascii=False)
    OUT.write_text("// Generated by tools/export_sim.py from cards/base_set.py and cards/foes.py. Do not edit.\n"
                   f"globalThis.BEARERS_CARDS = {body};\n"
                   'if (typeof module !== "undefined") module.exports = globalThis.BEARERS_CARDS;\n', encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
